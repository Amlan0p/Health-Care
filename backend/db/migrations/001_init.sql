-- 001_init.sql — initial PostgreSQL schema.
-- Mirrors the original SQLite tables (users, appointments, medications, vitals)
-- and adds the tables needed by the new backend features.

CREATE TABLE users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT        NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
  email         TEXT        NOT NULL CHECK (char_length(email) <= 254),
  password_hash TEXT        NOT NULL,
  is_demo       BOOLEAN     NOT NULL DEFAULT FALSE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Case-insensitive uniqueness (the app also lowercases emails before storing).
CREATE UNIQUE INDEX users_email_lower_key ON users (lower(email));

CREATE TABLE appointments (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  doctor_id   TEXT        NOT NULL,
  doctor      TEXT        NOT NULL,
  spec        TEXT        NOT NULL,
  hospital    TEXT        NOT NULL,
  appt_date   DATE        NOT NULL,
  appt_time   TIME        NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, doctor_id, appt_date, appt_time)
);
CREATE INDEX appointments_user_idx ON appointments (user_id, appt_date, appt_time);

CREATE TABLE medications (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name        TEXT        NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
  schedule    TEXT        NOT NULL CHECK (char_length(schedule) BETWEEN 1 AND 100),
  status      TEXT        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','taken','missed')),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX medications_user_idx ON medications (user_id, id);

CREATE TABLE vitals (
  user_id     INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  key         TEXT        NOT NULL CHECK (char_length(key) <= 40),
  value       TEXT        NOT NULL CHECK (char_length(value) <= 40),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, key)
);

-- Per-user AI chat history (scoped by user_id; never shared between accounts).
CREATE TABLE chat_messages (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role        TEXT        NOT NULL CHECK (role IN ('user','assistant')),
  content     TEXT        NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX chat_messages_user_idx ON chat_messages (user_id, id);

-- Logout support: a signed token's jti is recorded here until it would expire anyway.
CREATE TABLE revoked_tokens (
  jti         TEXT        PRIMARY KEY,
  expires_at  TIMESTAMPTZ NOT NULL
);
CREATE INDEX revoked_tokens_exp_idx ON revoked_tokens (expires_at);

-- Public forms. Rows are stored; no email is sent by this application.
CREATE TABLE contact_messages (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT        NOT NULL,
  email       TEXT        NOT NULL,
  subject     TEXT        NOT NULL DEFAULT '',
  message     TEXT        NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE newsletter_subscribers (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       TEXT        NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX newsletter_email_lower_key ON newsletter_subscribers (lower(email));
