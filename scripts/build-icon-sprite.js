'use strict';
/**
 * Builds frontend/assets/icons/sprite.svg from the individual Lucide SVG files in the same folder.
 * Usage: node scripts/build-icon-sprite.js
 * To add an icon: copy <name>.svg from lucide-static (https://lucide.dev, ISC licence) into
 * frontend/assets/icons/, then re-run this script. Icons are referenced as <use href="…/sprite.svg#<name>">.
 */
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'frontend', 'assets', 'icons');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.svg') && f !== 'sprite.svg').sort();
const symbols = files.map((f) => {
  const name = f.replace(/\.svg$/, '');
  const inner = fs.readFileSync(path.join(dir, f), 'utf8')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .trim();
  return `  <symbol id="${name}" viewBox="0 0 24 24">\n    ${inner.replace(/\n\s*/g, '\n    ')}\n  </symbol>`;
});
const out = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n  <!-- Generated by scripts/build-icon-sprite.js from Lucide icons (ISC licence, see LICENSE.txt). Do not edit by hand. -->\n${symbols.join('\n')}\n</svg>\n`;
fs.writeFileSync(path.join(dir, 'sprite.svg'), out);
console.log(`sprite.svg: ${files.length} icons, ${out.length} bytes`);
